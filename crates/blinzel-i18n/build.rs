//! Turns `i18n/<lang>.toml` into static tables at compile time.
//!
//! The generated code contains one `Msg` enum (keys of the English reference
//! file) and one `[&str; N]` table per language, so a translation at runtime is
//! a single array index. Missing translations fall back to English at build
//! time and are listed in `MISSING`; a placeholder mismatch is a build error.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

const REFERENCE: &str = "en";
const PLURAL_CATEGORIES: [&str; 6] = ["zero", "one", "two", "few", "many", "other"];

struct Language {
    code: String,
    name: String,
    plural_rule: String,
    simple: BTreeMap<String, String>,
    plural: BTreeMap<String, BTreeMap<String, String>>,
}

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let dir = manifest.join("../../i18n");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut langs = Vec::new();
    let mut entries: Vec<_> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "toml"))
        .collect();
    entries.sort();
    for path in entries {
        println!("cargo:rerun-if-changed={}", path.display());
        langs.push(load(&path));
    }
    // Reference language first, so its index is stable and it is the fallback.
    langs.sort_by_key(|l| (l.code != REFERENCE, l.code.clone()));
    assert!(
        langs.first().is_some_and(|l| l.code == REFERENCE),
        "i18n/{REFERENCE}.toml is required"
    );

    let reference = &langs[0];
    let simple_keys: Vec<&String> = reference.simple.keys().collect();
    let plural_keys: Vec<&String> = reference.plural.keys().collect();

    let mut missing = Vec::new();
    let mut errors = Vec::new();
    for lang in &langs[1..] {
        for key in lang.simple.keys().chain(lang.plural.keys()) {
            if !reference.simple.contains_key(key) && !reference.plural.contains_key(key) {
                errors.push(format!(
                    "{}: unknown key `{key}` (not in {REFERENCE}.toml)",
                    lang.code
                ));
            }
        }
        for key in &simple_keys {
            match lang.simple.get(*key) {
                Some(text) => {
                    check_placeholders(&mut errors, lang, key, text, &reference.simple[*key])
                }
                None => missing.push((lang.code.clone(), (*key).clone())),
            }
        }
        for key in &plural_keys {
            match lang.plural.get(*key) {
                Some(forms) => {
                    let reference_other = &reference.plural[*key]["other"];
                    for (cat, text) in forms {
                        check_placeholders(&mut errors, lang, key, text, reference_other);
                        if !PLURAL_CATEGORIES.contains(&cat.as_str()) {
                            errors.push(format!(
                                "{}: `{key}` has unknown plural category `{cat}`",
                                lang.code
                            ));
                        }
                    }
                }
                None => missing.push((lang.code.clone(), (*key).clone())),
            }
        }
    }
    if !errors.is_empty() {
        panic!("i18n errors:\n{}", errors.join("\n"));
    }
    for (lang, key) in &missing {
        println!("cargo:warning=i18n: `{key}` is not translated to `{lang}`, using English");
    }

    let mut out = String::new();
    out.push_str("// @generated by build.rs from i18n/*.toml. Do not edit.\n\n");

    let _ = writeln!(
        out,
        "/// Number of simple messages.\npub const MSG_COUNT: usize = {};",
        simple_keys.len()
    );
    let _ = writeln!(
        out,
        "/// Number of plural messages.\npub const PLURAL_MSG_COUNT: usize = {};",
        plural_keys.len()
    );
    let _ = writeln!(
        out,
        "/// Number of languages.\npub const LANG_COUNT: usize = {};\n",
        langs.len()
    );

    emit_enum(&mut out, "Msg", "A translatable message.", &simple_keys);
    emit_enum(
        &mut out,
        "PluralMsg",
        "A translatable message with plural forms.",
        &plural_keys,
    );

    let lang_idents: Vec<String> = langs.iter().map(|l| camel(&l.code)).collect();
    out.push_str("/// A language that ships with the application.\n");
    out.push_str(
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[repr(u8)]\npub enum Lang {\n",
    );
    for (ident, lang) in lang_idents.iter().zip(&langs) {
        let _ = writeln!(out, "    /// {}", lang.name);
        let _ = writeln!(out, "    {ident},");
    }
    out.push_str("}\n\nimpl Lang {\n");
    let _ = writeln!(
        out,
        "    /// All languages; the reference language comes first.\n    pub const ALL: [Lang; LANG_COUNT] = [{}];",
        lang_idents
            .iter()
            .map(|i| format!("Lang::{i}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    out.push_str("    /// BCP 47 code, e.g. `de`.\n    pub const fn code(self) -> &'static str {\n        match self {\n");
    for (ident, lang) in lang_idents.iter().zip(&langs) {
        let _ = writeln!(out, "            Lang::{ident} => {:?},", lang.code);
    }
    out.push_str("        }\n    }\n    /// Name of the language in that language, e.g. `Deutsch`.\n    pub const fn native_name(self) -> &'static str {\n        match self {\n");
    for (ident, lang) in lang_idents.iter().zip(&langs) {
        let _ = writeln!(out, "            Lang::{ident} => {:?},", lang.name);
    }
    out.push_str("        }\n    }\n    pub(crate) const fn plural_rule(self) -> crate::plural::Rule {\n        match self {\n");
    for (ident, lang) in lang_idents.iter().zip(&langs) {
        let _ = writeln!(
            out,
            "            Lang::{ident} => crate::plural::Rule::{},",
            plural_rule_ident(&lang.plural_rule, &lang.code)
        );
    }
    out.push_str("        }\n    }\n}\n\n");

    out.push_str("pub(crate) static TABLE: [[&str; MSG_COUNT]; LANG_COUNT] = [\n");
    for lang in &langs {
        let _ = writeln!(out, "    // {}", lang.code);
        out.push_str("    [\n");
        for key in &simple_keys {
            let text = lang.simple.get(*key).unwrap_or(&reference.simple[*key]);
            let _ = writeln!(out, "        {text:?},");
        }
        out.push_str("    ],\n");
    }
    out.push_str("];\n\n");

    out.push_str(
        "pub(crate) static PLURAL_TABLE: [[[&str; 6]; PLURAL_MSG_COUNT]; LANG_COUNT] = [\n",
    );
    for lang in &langs {
        let _ = writeln!(out, "    // {}", lang.code);
        out.push_str("    [\n");
        for key in &plural_keys {
            let forms = lang.plural.get(*key).unwrap_or(&reference.plural[*key]);
            let other = forms.get("other").expect("plural message without `other`");
            let row: Vec<String> = PLURAL_CATEGORIES
                .iter()
                .map(|c| format!("{:?}", forms.get(*c).unwrap_or(other)))
                .collect();
            let _ = writeln!(out, "        [{}],", row.join(", "));
        }
        out.push_str("    ],\n");
    }
    out.push_str("];\n\n");

    out.push_str("/// Translations that fell back to English at build time: (language, key).\n");
    out.push_str("pub static MISSING: &[(&str, &str)] = &[\n");
    for (lang, key) in &missing {
        let _ = writeln!(out, "    ({lang:?}, {key:?}),");
    }
    out.push_str("];\n");

    let out_path = PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("generated.rs");
    fs::write(out_path, out).unwrap();
}

fn load(path: &Path) -> Language {
    let code = path.file_stem().unwrap().to_string_lossy().to_lowercase();
    let text = fs::read_to_string(path).unwrap();
    let doc: toml::Table = text
        .parse()
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let meta = doc.get("meta").and_then(|m| m.as_table());
    let name = meta
        .and_then(|m| m.get("name"))
        .and_then(|v| v.as_str())
        .unwrap_or_else(|| panic!("{}: missing [meta] name", path.display()))
        .to_owned();
    let plural_rule = meta
        .and_then(|m| m.get("plural"))
        .and_then(|v| v.as_str())
        .unwrap_or("auto")
        .to_owned();

    let mut simple = BTreeMap::new();
    let mut plural = BTreeMap::new();
    let messages = doc
        .get("messages")
        .and_then(|m| m.as_table())
        .unwrap_or_else(|| panic!("{}: missing [messages]", path.display()));
    for (key, value) in messages {
        assert!(
            key.chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "{}: key `{key}` must be snake_case",
            path.display()
        );
        match value {
            toml::Value::String(s) => {
                simple.insert(key.clone(), s.clone());
            }
            toml::Value::Table(t) => {
                let forms = t
                    .iter()
                    .map(|(cat, v)| {
                        let s = v.as_str().unwrap_or_else(|| {
                            panic!("{}: `{key}.{cat}` must be a string", path.display())
                        });
                        (cat.clone(), s.to_owned())
                    })
                    .collect::<BTreeMap<_, _>>();
                assert!(
                    forms.contains_key("other"),
                    "{}: plural message `{key}` needs an `other` form",
                    path.display()
                );
                plural.insert(key.clone(), forms);
            }
            _ => panic!(
                "{}: `{key}` must be a string or a plural table",
                path.display()
            ),
        }
    }
    Language {
        code,
        name,
        plural_rule,
        simple,
        plural,
    }
}

fn placeholders(text: &str) -> BTreeSet<String> {
    let mut set = BTreeSet::new();
    let mut rest = text;
    while let Some(start) = rest.find('{') {
        let after = &rest[start + 1..];
        let Some(end) = after.find('}') else { break };
        set.insert(after[..end].to_owned());
        rest = &after[end + 1..];
    }
    set
}

fn check_placeholders(
    errors: &mut Vec<String>,
    lang: &Language,
    key: &str,
    text: &str,
    reference: &str,
) {
    let have = placeholders(text);
    let want = placeholders(reference);
    if have != want {
        errors.push(format!(
            "{}: `{key}` has placeholders {have:?}, {REFERENCE} has {want:?}",
            lang.code
        ));
    }
}

fn emit_enum(out: &mut String, name: &str, doc: &str, keys: &[&String]) {
    let _ = writeln!(out, "/// {doc}");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[repr(u16)]\n");
    let _ = writeln!(out, "pub enum {name} {{");
    for key in keys {
        let _ = writeln!(out, "    /// `{key}`");
        let _ = writeln!(out, "    {},", camel(key));
    }
    out.push_str("}\n\n");
    let _ = writeln!(out, "impl {name} {{");
    let _ = writeln!(
        out,
        "    /// Every message, in table order.\n    pub const ALL: [{name}; {}] = [{}];",
        keys.len(),
        keys.iter()
            .map(|k| format!("{name}::{}", camel(k)))
            .collect::<Vec<_>>()
            .join(", ")
    );
    out.push_str("    /// The key as written in the TOML files.\n    pub const fn key(self) -> &'static str {\n        match self {\n");
    for key in keys {
        let _ = writeln!(out, "            {name}::{} => {key:?},", camel(key));
    }
    out.push_str("        }\n    }\n}\n\n");
}

fn camel(key: &str) -> String {
    key.split(['_', '-'])
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            let first = c.next().unwrap().to_ascii_uppercase();
            std::iter::once(first).chain(c).collect::<String>()
        })
        .collect()
}

fn plural_rule_ident(rule: &str, code: &str) -> &'static str {
    let rule = if rule == "auto" {
        match code.split('-').next().unwrap() {
            "fr" | "pt" => "zero-one-other",
            "ru" | "uk" | "be" => "east-slavic",
            "pl" => "polish",
            "cs" | "sk" => "czech",
            "ja" | "zh" | "ko" | "vi" | "th" | "id" => "none",
            _ => "one-other",
        }
    } else {
        rule
    };
    match rule {
        "one-other" => "OneOther",
        "zero-one-other" => "ZeroOneOther",
        "east-slavic" => "EastSlavic",
        "polish" => "Polish",
        "czech" => "Czech",
        "none" => "None",
        other => panic!("unknown plural rule `{other}` for `{code}`"),
    }
}

// --------------------------------------------------------- contrast (AC-10)

/// Relative luminance of `0xRRGGBB` (WCAG 2.1).
fn luminance(hex: u32) -> f64 {
    let channel = |shift: u32| {
        let c = ((hex >> shift) & 0xFF) as f64 / 255.0;
        if c <= 0.04045 {
            c / 12.92
        } else {
            ((c + 0.055) / 1.055).powf(2.4)
        }
    };
    0.2126 * channel(16) + 0.7152 * channel(8) + 0.0722 * channel(0)
}

/// The contrast ratio of two colours (WCAG 2.1).
fn contrast(a: u32, b: u32) -> f64 {
    let (la, lb) = (luminance(a), luminance(b));
    (la.max(lb) + 0.05) / (la.min(lb) + 0.05)
}

#[test]
fn contrast_follows_the_wcag_formula() {
    assert!((contrast(0x000000, 0xFFFFFF) - 21.0).abs() < 1e-9);
    assert!((contrast(0x777777, 0xFFFFFF) - 4.478).abs() < 0.01);
    assert_eq!(contrast(0x123456, 0x123456), 1.0);
}

/// AC-10: text reaches 4.5 : 1 on both surfaces and on the accent fill,
/// accent lines and the focus outline 3 : 1 on `surface`.
#[test]
fn the_dark_palette_passes_wcag_aa() {
    let p = DARK;
    for (name, ink) in [
        ("text", p.text),
        ("text_secondary", p.text_secondary),
        ("text_muted", p.text_muted),
        ("danger_ink", p.danger_ink),
        ("accent_ink", p.accent_ink),
    ] {
        for (ground_name, ground) in [("surface", p.surface), ("surface_raised", p.surface_raised)]
        {
            let c = contrast(ink, ground);
            assert!(c >= 4.5, "{name} on {ground_name}: {c:.2}");
        }
    }
    let c = contrast(p.on_accent, p.accent_solid);
    assert!(c >= 4.5, "on_accent on accent_solid: {c:.2}");
    for (name, line) in [("accent", p.accent), ("focus", p.focus)] {
        let c = contrast(line, p.surface);
        assert!(c >= 3.0, "{name} on surface: {c:.2}");
    }
}

// ------------------------------------------------------- background (AC-11)

/// AC-11: without a settings file the area around the image is the
/// theme's `bg`.
#[test]
fn the_default_background_is_the_themes_bg() {
    let [r, g, b] = Settings::default().background;
    let hex = (r as u32) << 16 | (g as u32) << 8 | b as u32;
    assert_eq!(hex, DARK.bg);
    let h = Harness::new();
    assert_eq!(h.app.settings.background, [0x15, 0x16, 0x1A]);
}

/// The fills, outlines and lines of `shapes`, as (radius, colour).
fn fills(shapes: &[Shape]) -> Vec<(f32, Rgba)> {
    shapes
        .iter()
        .filter_map(|s| match s {
            Shape::Fill { radius, color, .. } => Some((*radius, *color)),
            _ => None,
        })
        .collect()
}

fn outlines(shapes: &[Shape]) -> Vec<(f32, Rgba)> {
    shapes
        .iter()
        .filter_map(|s| match s {
            Shape::Outline { radius, color, .. } => Some((*radius, *color)),
            _ => None,
        })
        .collect()
}

fn lines(shapes: &[Shape]) -> Vec<Rgba> {
    shapes
        .iter()
        .filter_map(|s| match s {
            Shape::Line { color, .. } => Some(*color),
            _ => None,
        })
        .collect()
}

/// What one widget draws at scale 1.
fn drawn(draw: impl FnOnce(&mut Painter<FakeCanvas>)) -> crate::testkit::Frame {
    let mut canvas = FakeCanvas::default();
    let mut p = Painter {
        canvas: &mut canvas,
        scale: 1.0,
    };
    draw(&mut p);
    canvas.frame
}


/// The production part of each source file of this crate that may not
/// name a colour: everything but the primitives (`gfx.rs`), the adapter,
/// the generated module and tests.
fn interface_sources() -> Vec<(String, String)> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut out = Vec::new();
    for entry in std::fs::read_dir(&dir).unwrap() {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_string_lossy().into_owned();
        let skip = ["gfx.rs", "palette.rs", "theme.rs", "testkit.rs"];
        if !name.ends_with(".rs") || name.ends_with("_tests.rs") || skip.contains(&name.as_str()) {
            continue;
        }
        let text = read(&path);
        let code = text.split("\n#[cfg(test)]\nmod tests").next().unwrap();
        out.push((name, code.to_string()));
    }
    assert!(out.len() > 10, "found the sources");
    out
}

/// The colour literals (`Rgba(r, g, b, a)` with numbers) in `code`.
fn colour_literals(code: &str) -> Vec<[f32; 3]> {
    code.split("Rgba(")
        .skip(1)
        .filter_map(|rest| {
            let args = rest.split(')').next()?;
            let mut n = args.split(',').map(|a| a.trim().parse::<f32>());
            Some([n.next()?.ok()?, n.next()?.ok()?, n.next()?.ok()?])
        })
        .collect()
}

#[test]
fn colour_literals_are_found_also_over_several_lines() {
    let code = "let a = Rgba(0.5, 0.25, 1.0, 1.0);\nfn f(c: Rgba) {}\nRgba(\n    0.0,\n    0.0,\n    0.0,\n    0.4,\n)\nRgba(r, g, b, a)";
    assert_eq!(colour_literals(code), [[0.5, 0.25, 1.0], [0.0, 0.0, 0.0]]);
}

/// AC-03: outside the adapter no source names a colour other than black
/// or white (with alpha: what is drawn over the picture).
#[test]
fn no_colour_literal_outside_the_adapter() {
    let mut found = Vec::new();
    for (name, code) in interface_sources() {
        for c in colour_literals(&code) {
            if c != [0.0; 3] && c != [1.0; 3] {
                found.push(format!("{name}: Rgba({}, {}, {}, …)", c[0], c[1], c[2]));
            }
        }
    }
    assert!(found.is_empty(), "{found:#?}");
}


/// AC-05, AC-06, AC-09: buttons. Primary: `accent_solid` with
/// `on_accent` text, lighter under the pointer; secondary:
/// `surface_raised`, `hover` under the pointer; disabled (edge case):
/// `surface_raised` with `text_muted`, also a primary one.

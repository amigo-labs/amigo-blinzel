fn is_former_blue(c: &[f32; 3]) -> bool {
    *c == [0.35, 0.62, 1.0] || *c == [0.0, 0.47, 0.84]
}

/// AC-08: the former blue is gone from every source of this crate, and
/// the accent roles are red.
#[test]
fn the_former_blue_is_gone() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut sources: Vec<(String, String)> = ["palette.rs", "gfx.rs"]
        .iter()
        .map(|n| (n.to_string(), read(&dir.join(n))))
        .collect();
    sources.extend(interface_sources());
    for (name, code) in sources {
        assert!(
            !colour_literals(&code).iter().any(is_former_blue),
            "{name} still names the blue accent"
        );
    }
    for c in [
        palette::ACCENT,
        palette::ACCENT_INK,
        palette::ACCENT_SOLID,
        palette::ACCENT_TINT,
        palette::FOCUS,
    ] {
        assert!(c.0 > c.2, "{c:?} is red, not blue");
    }
}


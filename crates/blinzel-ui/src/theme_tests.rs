    let f = drawn(|p| p.button("Cancel", false, true, true, r));
    assert_eq!(fills(&f.shapes), [(small, palette::CONTROL_HOVER)]);

    for (primary, hover) in [(true, false), (true, true), (false, true)] {
        let f = drawn(|p| p.button("Start", primary, hover, false, r));
        assert_eq!(fills(&f.shapes), [(small, palette::CONTROL)]);
        assert_eq!(f.text_colors, [palette::FAINT]);
    }
